import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// Macrobenchmarks (M4.1), run on the real TV against the shipped release build:
//   tools/gw.sh :benchmark:connectedBenchmarkAndroidTest      (recipe: docs/perf-budget.md §How to run)
// The "benchmark" build type of this module is matched with :app's `release` variant (R8 on, signed
// with the debug key, <profileable> in the manifest), i.e. exactly the APK that is installed on the TV.
plugins {
    alias(libs.plugins.android.test)
}

android {
    namespace = "app.bolbol.tv.benchmark"
    compileSdk = libs.versions.compileSdk.get().toInt()
    defaultConfig {
        minSdk = libs.versions.minSdk.get().toInt()
        targetSdk = libs.versions.targetSdk.get().toInt()
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }
    targetProjectPath = ":app"
    // Macrobenchmark needs a self-instrumenting test APK: it drives (and kills/restarts) the target app
    // from the outside instead of instrumenting it.
    experimentalProperties["android.experimental.self-instrumenting"] = true
    buildTypes {
        create("benchmark") {
            isDebuggable = true // the test APK only; the app under test is :app `release` (not debuggable)
            signingConfig = signingConfigs.getByName("debug") // same key as :app release, required to instrument
            matchingFallbacks += listOf("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    // Journeys shared with :baselineprofile, so the profile is generated by the flows that are measured.
    sourceSets.getByName("main").kotlin.srcDir("../baselineprofile/src/journeys/kotlin")
}

kotlin { compilerOptions { jvmTarget.set(JvmTarget.JVM_17) } }

// Only the benchmark variant makes sense here (it has no debug counterpart in :app to measure).
androidComponents {
    beforeVariants(selector().all()) { it.enable = it.buildType == "benchmark" }
}

dependencies {
    implementation(libs.androidx.test.ext.junit)
    implementation(libs.androidx.test.runner)
    implementation(libs.androidx.uiautomator)
    implementation(libs.androidx.benchmark.macro)
}
